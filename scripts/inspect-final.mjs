import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5180/');
await page.waitForTimeout(1800);
await page.screenshot({path:'artifacts/15-laptop-home.png',fullPage:true});
await page.getByRole('button',{name:/Design Next Step/}).click();
await expect(page.getByRole('dialog')).toBeVisible();
await page.keyboard.press('Tab');
if(!await page.evaluate(()=>!!document.activeElement?.closest('[role="dialog"]')))throw new Error('Modal focus escaped');
await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
await page.getByRole('button',{name:/03.*LADERAS Y TERRITORIO/}).click();
await page.getByRole('button',{name:/01 Altos de la Estancia/}).click();
await page.getByRole('button',{name:'Configurar escenario',exact:true}).click();
await page.getByRole('button',{name:'Visualizar deslizamiento',exact:true}).click();
await expect(page.locator('.three-host canvas')).toBeVisible();
await expect(page.getByRole('dialog').getByRole('slider',{name:'Tiempo del escenario'})).toHaveValue('100');
await page.waitForTimeout(1700);
await page.screenshot({path:'artifacts/16-landslide-deposit.png',fullPage:true});
await page.getByRole('button',{name:'Cerrar ventana'}).click();
await page.getByRole('button',{name:'Capas del mapa'}).click();
await page.getByRole('button',{name:'Relieve regional 3D',exact:true}).click();
await page.waitForTimeout(2000);
await page.getByRole('button',{name:'Relieve regional 3D',exact:true}).click();
await page.getByRole('button',{name:'Capas del mapa'}).click();
await page.getByRole('button',{name:'Evaluar impacto económico'}).click();
await page.emulateMedia({media:'print'});
await page.pdf({path:'artifacts/ejemplo-impacto.pdf',format:'A4',printBackground:true});
await page.close();
const offline=await browser.newPage({viewport:{width:1366,height:768}});
await offline.route(/^https:\/\//,r=>r.abort());
await offline.goto('http://127.0.0.1:5180/');
await offline.getByRole('button',{name:/01.*CUENCAS DE MONTAÑA/}).click();
await expect(offline.locator('.map-label').first()).toBeVisible();
await offline.waitForTimeout(1800);
await offline.screenshot({path:'artifacts/17-offline-context.png',fullPage:true});
fs.writeFileSync('artifacts/final-inspection.json',JSON.stringify({errors,viewport:'1366 × 768',reducedMotion:true,keyboardModal:true,terrainToggle:true,printPdf:true,externalNetworkBlocked:true},null,2));
console.log('Final inspection',errors);
await browser.close();
