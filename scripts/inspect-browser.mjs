import { chromium } from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1512,height:982},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,300));});
await page.goto('http://127.0.0.1:5180/',{waitUntil:'networkidle'});
await page.waitForTimeout(3000);
await page.screenshot({path:'artifacts/01-home.png',fullPage:true});
console.log('HOME',await page.title(),await page.locator('h1').innerText(),errors);
await page.getByRole('button',{name:/01.*CUENCAS DE MONTAÑA/}).click();
await page.waitForTimeout(1600);
await page.screenshot({path:'artifacts/02-territories.png',fullPage:true});
await page.getByRole('button',{name:/01 Quebrada Chiguaza/}).click();
await page.waitForTimeout(1700);
await page.screenshot({path:'artifacts/03-chiguaza.png',fullPage:true});
await page.getByRole('button',{name:'Simular una lluvia',exact:true}).click();
await page.screenshot({path:'artifacts/04-scenario.png',fullPage:true});
await page.getByRole('button',{name:'Visualizar escenario',exact:true}).click();
await page.waitForTimeout(7000);
await page.screenshot({path:'artifacts/05-results.png',fullPage:true});
await page.getByRole('button',{name:'Evaluar impacto económico'}).click();
await page.screenshot({path:'artifacts/06-impact.png',fullPage:true});
console.log('ERRORS',errors);fs.writeFileSync('artifacts/browser-errors.json',JSON.stringify(errors,null,2));
await browser.close();
